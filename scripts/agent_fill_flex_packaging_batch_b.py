def main() -> None:
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = FP.with_name(FP.stem + f"_backup_before_agent_fill_b_{stamp}.xlsx")
    shutil.copy2(FP, backup)

    wb = load_workbook(FP)
    ws = wb.active
    headers = [c.value for c in next(ws.iter_rows(min_row=1, max_row=1))]
    hidx = {str(h): i for i, h in enumerate(headers)}

    updated = []
    missing_names = []
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        name = str(row[0].value or "").strip()
        if name not in VERIFIED:
            continue
        fields = VERIFIED[name]
        changed = []
        for col, val in fields.items():
            if not val or not str(val).strip():
                continue
            if col not in hidx:
                continue
            if col in {"Contact Person", "Role", "Email", "LinkedIn", "Office No."}:
                continue
            cell = row[hidx[col]]
            cur = cell.value
            if cur is None or str(cur).strip() == "":
                cell.value = val
                changed.append(col)
        if changed:
            updated.append(f"{name}: {len(changed)} cols")
        else:
            missing_names.append(name)

    for cell in ws[1]:
        cell.font = Font(bold=True)
    wb.save(FP)

    wb2 = load_workbook(FP, read_only=True, data_only=True)
    ws2 = wb2.active
    rows = list(ws2.iter_rows(min_row=2, values_only=True))
    wb2.close()
    hq = sum(1 for r in rows if r[3] not in (None, ""))
    print(f"backup: {backup}")
    print(f"companies_updated: {len(updated)}")
    for u in updated:
        print(" ", u)
    print(f"no_empty_cells_to_fill: {missing_names}")
    print("--- fill rates ---")
    for i, h in enumerate(headers):
        n = sum(1 for r in rows if r[i] not in (None, ""))
        print(f"  {n}/{len(rows)}  {h}")
    print(f"HQ_filled_now: {hq}/{len(rows)}")


if __name__ == "__main__":
    main()
