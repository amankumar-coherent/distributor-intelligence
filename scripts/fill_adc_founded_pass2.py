FOUNDED_PATS = [
    re.compile(r"(?:founded|established|incorpora(?:ted|tion)|since|started|began|created)\s+(?:in\s+)?((?:18|19|20)\d{2})", re.I),
    re.compile(r"\best\.?\s*((?:18|19|20)\d{2})\b", re.I),
    re.compile(r"\bsince\s*((?:18|19|20)\d{2})\b", re.I),
    re.compile(r"((?:18|19|20)\d{2})\s*[-–]\s*(?:present|today)", re.I),
    re.compile(r"(?:year founded|founded year|founding year)\D{0,10}((?:18|19|20)\d{2})", re.I),
]


def empty(v: Any) -> bool:
    return str(v or "").strip().lower() in NPD


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "").strip().lower())


def lookup_extra(company: str) -> str:
    n = norm(company)
    if n in EXTRA:
        return EXTRA[n]
    for k, y in sorted(EXTRA.items(), key=lambda x: -len(x[0])):
        if len(k) >= 5 and k in n:
            return y
    return ""


def extract_year(text: str) -> str:
    for pat in FOUNDED_PATS:
        m = pat.search(text or "")
        if m:
            y = int(m.group(1))
            if 1800 <= y <= 2026:
                return str(y)
    return ""


async def ddg(client: httpx.AsyncClient, q: str) -> str:
    """DuckDuckGo HTML search (not SearXNG)."""
    try:
        r = await client.get(
            "https://html.duckduckgo.com/html/",
            params={"q": q},
            timeout=20.0,
            headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"},
        )
        if r.status_code != 200:
            return ""
        text = re.sub(r"(?is)<[^>]+>", " ", r.text)
        return re.sub(r"\s+", " ", text)[:12000]
    except Exception:
        return ""


async def wiki(client: httpx.AsyncClient, company: str) -> str:
    try:
        q = re.split(r"[/(]", company)[0].strip()
        r = await client.get(
            "https://en.wikipedia.org/w/api.php",
            params={"action": "query", "list": "search", "srsearch": q, "format": "json", "srlimit": 2},
            timeout=12.0,
            headers={"User-Agent": "vendor-intel-adc-fill2/1.0"},
        )
        hits = ((r.json().get("query") or {}).get("search") or [])
        tokens = [t for t in norm(company).split() if len(t) > 3][:2]
        for h in hits:
            title = h.get("title") or ""
            if tokens and not any(t in norm(title) for t in tokens):
                continue
            r2 = await client.get(
                f"https://en.wikipedia.org/api/rest_v1/page/summary/{quote(title)}",
                timeout=12.0,
                headers={"User-Agent": "vendor-intel-adc-fill2/1.0"},
            )
            if r2.status_code == 200:
                return str(r2.json().get("extract") or "")
    except Exception:
        return ""
    return ""


def load_rows(path: Path) -> list[dict[str, str]]:
    wb = load_workbook(path, data_only=True)
    ws = wb.active
    hdr = [c.value for c in ws[2]]
    rows = []
    for r in range(3, ws.max_row + 1):
        d = {str(h): str(ws.cell(r, i).value or "").strip() for i, h in enumerate(hdr, 1) if h}
        if d.get("Company"):
            rows.append(d)
    return rows


